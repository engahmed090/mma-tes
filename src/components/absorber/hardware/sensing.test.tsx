import { render, screen } from '@testing-library/react';
import { expect, it } from 'vitest';
import * as THREE from 'three';
import ResponsePanel from './ResponsePanel';
import { createSampleRig } from './sampleRig';
import { responseFor } from './response';
it('acquires a labelled illustration, holds it at result and clears on reset', () => {
  const {rerender} = render(<ResponsePanel sample="Healthy" time={0}/>);
  expect(screen.queryByTestId('response-curve')).toBeNull();
  rerender(<ResponsePanel sample="Healthy" time={8}/>);
  const partial = screen.getByTestId('response-curve').getAttribute('d')!;
  rerender(<ResponsePanel sample="Healthy" time={18}/>);
  expect(screen.getByTestId('response-curve').getAttribute('d')!.length).toBeGreaterThan(partial.length);
  expect(screen.getByText(/source calibration unverified/)).toBeTruthy();
  rerender(<ResponsePanel sample="JuiceElevated" time={0}/>);
  expect(screen.queryByTestId('response-curve')).toBeNull();
  expect(screen.getByText(/No nitrate calibration or measured source/)).toBeTruthy();
  expect(responseFor('JuiceElevated').type).toBe('synthetic/demo');
  expect(responseFor('Research').type).toBe('analytical/unverified');
});
it('moves liquid to the portable sensor, switches color, and restores original components exactly', () => {
  const scene = new THREE.Scene(), model = new THREE.Group(); scene.add(model);
  const part = new THREE.Mesh(new THREE.BoxGeometry(1,1,1), new THREE.MeshBasicMaterial());
  part.name = 'Mini | optical screen [web snapshot]'; part.position.set(1,2,3); model.add(part);
  const original = part.position.clone();
  const sensor = part.clone(); sensor.name = 'Mini | metamaterial PCB [web snapshot]'; model.add(sensor);
  const rig = createSampleRig(model, scene, true);
  rig.update(6,'JuiceReference',true,1);
  const cartridge = scene.getObjectByName('Illustrative liquid cartridge')!;
  expect(cartridge.visible).toBe(true);
  const liquid = cartridge.children[1] as THREE.Mesh<THREE.BufferGeometry, THREE.MeshStandardMaterial>;
  expect(liquid.material.color.getHexString()).toBe('ff980a');
  expect(part.position.y).toBeGreaterThan(original.y);
  for(let i=0;i<100;i++) rig.update(6,'Healthy',false,.1);
  expect(part.position.equals(original)).toBe(true);
  expect(liquid.material.color.getHexString()).toBe('880e24');
  rig.reset(); expect(cartridge.visible).toBe(false);
  expect(part.position.equals(original)).toBe(true);
  rig.dispose(); expect(scene.getObjectByName('Illustrative liquid cartridge')).toBeUndefined();
});
